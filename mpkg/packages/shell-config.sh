# Writes the environment this prefix needs into a single sourceable file and
# wires it into ~/.zshrc through a marked block. The old installer overwrote
# ~/.zshrc wholesale; this only ever replaces its own block.

mpkg_inherit pkgcommon

MPKG_TITLE="Shell configuration"
MPKG_DESC="mpkg env file plus the ~/.zshrc block that sources it"
MPKG_KIND="config"
MPKG_UNVERSIONED=1
MPKG_PROBE_CMD="zsh"
MPKG_DEPENDS=(oh-my-zsh starship)
MPKG_REQUIRES_CMD=(zsh)

MPKG_ENV_FILE="${MPKG_PREFIX}/share/mpkg/env.sh"
MPKG_MARK_BEGIN="# >>> mpkg >>>"
MPKG_MARK_END="# <<< mpkg <<<"

mpkg_run() {
    mpkg::shell_write_env || return 1
    mpkg::shell_patch_rc "${HOME}/.zshrc" || return 1
    MPKG_VERSION="present"
    MPKG_DEST_NAME=""
    MPKG_STATUS="installed"
}

mpkg::shell_write_env() {
    mkdir -p "$(dirname "${MPKG_ENV_FILE}")" || return 1
    mpkg::step "writing ${MPKG_ENV_FILE}"
    {
        printf '# Generated by mpkg on %s. Edits are overwritten.\n\n' "$(date -u +%F)"
        printf 'export MPKG_PREFIX="%s"\n\n' "${MPKG_PREFIX}"
        cat <<'BODY'
# POSIX sh, no ${!var}: this file is sourced by zsh as well as bash.
mpkg_path_prepend() {
    eval "_mpkg_cur=\${$1:-}"
    case ":${_mpkg_cur}:" in *":$2:"*) return 0 ;; esac
    if [ -n "${_mpkg_cur}" ]; then eval "export $1=\"\$2:\${_mpkg_cur}\""
    else                           eval "export $1=\"\$2\""
    fi
}

mpkg_path_prepend PATH            "${MPKG_PREFIX}/bin"
mpkg_path_prepend PATH            "${HOME}/.cargo/bin"
mpkg_path_prepend CPATH           "${MPKG_PREFIX}/include"
mpkg_path_prepend LIBRARY_PATH    "${MPKG_PREFIX}/lib"
mpkg_path_prepend LIBRARY_PATH    "${MPKG_PREFIX}/lib64"
mpkg_path_prepend LD_LIBRARY_PATH "${MPKG_PREFIX}/lib"
mpkg_path_prepend LD_LIBRARY_PATH "${MPKG_PREFIX}/lib64"
mpkg_path_prepend MANPATH         "${MPKG_PREFIX}/share/man"
mpkg_path_prepend PKG_CONFIG_PATH "${MPKG_PREFIX}/lib/pkgconfig"
mpkg_path_prepend PKG_CONFIG_PATH "${MPKG_PREFIX}/lib64/pkgconfig"

# GTK finds its GSettings schemas, and desktops find zathura, through
# XDG_DATA_DIRS. Unset means the spec's default, which has to be kept.
[ -n "${XDG_DATA_DIRS:-}" ] || export XDG_DATA_DIRS="/usr/local/share:/usr/share"
mpkg_path_prepend XDG_DATA_DIRS   "${MPKG_PREFIX}/share"

# JDK (mpkg install jdk)
[ -x "${MPKG_PREFIX}/libexec/jdk/bin/java" ] && export JAVA_HOME="${MPKG_PREFIX}/libexec/jdk"
BODY
        [[ -n "${MPKG_CA_BUNDLE}" ]] && \
            printf '\nexport SSL_CERT_FILE="%s"\nexport CURL_CA_BUNDLE="%s"\n' \
                   "${MPKG_CA_BUNDLE}" "${MPKG_CA_BUNDLE}"
        cat <<'BODY'

# mpkg environments:  mpkg_activate <name>  /  mpkg_deactivate
mpkg_activate() {
    if [ -f "${MPKG_PREFIX}/envs/$1/activate" ]; then . "${MPKG_PREFIX}/envs/$1/activate"
    else echo "mpkg_activate: no environment '$1'" >&2; return 1
    fi
}

# Oh My Zsh
if [ -d "${HOME}/.oh-my-zsh" ] && [ -n "${ZSH_VERSION:-}" ]; then
    export ZSH="${HOME}/.oh-my-zsh"
    ZSH_THEME="robbyrussell"
    plugins=(git zsh-autosuggestions zsh-syntax-highlighting)
    . "${ZSH}/oh-my-zsh.sh"
fi

# Starship prompt
if command -v starship >/dev/null 2>&1; then
    [ -f "${HOME}/.config/starship/jetpack.toml" ] && \
        export STARSHIP_CONFIG="${HOME}/.config/starship/jetpack.toml"
    if [ -n "${ZSH_VERSION:-}" ]; then eval "$(starship init zsh)"
    elif [ -n "${BASH_VERSION:-}" ]; then eval "$(starship init bash)"
    fi
fi

# Rust
[ -s "${HOME}/.cargo/env" ] && . "${HOME}/.cargo/env"

# nvm
export NVM_DIR="${HOME}/.nvm"
[ -s "${NVM_DIR}/nvm.sh" ] && . "${NVM_DIR}/nvm.sh"

# RVM (last: it wants its own PATH entries first)
[ -s "${HOME}/.rvm/scripts/rvm" ] && . "${HOME}/.rvm/scripts/rvm"
BODY
    } > "${MPKG_ENV_FILE}"
}

mpkg::shell_patch_rc() {
    local rc="$1" tmp
    touch "${rc}" || return 1
    if grep -qF "${MPKG_MARK_BEGIN}" "${rc}"; then
        mpkg::step "refreshing the mpkg block in ${rc}"
        tmp="$(mktemp)"
        awk -v b="${MPKG_MARK_BEGIN}" -v e="${MPKG_MARK_END}" \
            'index($0,b){s=1} !s{print} index($0,e){s=0}' "${rc}" > "${tmp}"
        mv "${tmp}" "${rc}"
    else
        mpkg::step "adding an mpkg block to ${rc}"
        cp "${rc}" "${rc}.mpkg-backup.$(date +%s)" 2>/dev/null
    fi
    {
        printf '%s\n' "${MPKG_MARK_BEGIN}"
        printf '[ -f "%s" ] && . "%s"\n' "${MPKG_ENV_FILE}" "${MPKG_ENV_FILE}"
        printf '%s\n' "${MPKG_MARK_END}"
    } >> "${rc}"
}

mpkg_link() { return 0; }

mpkg_remove() {
    local rc="${HOME}/.zshrc" tmp
    [[ -f "${rc}" ]] || return 0
    tmp="$(mktemp)"
    awk -v b="${MPKG_MARK_BEGIN}" -v e="${MPKG_MARK_END}" \
        'index($0,b){s=1} !s{print} index($0,e){s=0}' "${rc}" > "${tmp}"
    mv "${tmp}" "${rc}"
    rm -f "${MPKG_ENV_FILE}"
}
