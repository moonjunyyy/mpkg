# Meson is pure Python and runs straight from its release tarball, so there is
# nothing to build: the tree goes to libexec/ and bin/meson is a launcher that
# finds a Python 3 at run time (the system's, or the one uv installed).

mpkg_inherit tarcommon

MPKG_TITLE="Meson"
MPKG_DESC="Build system used by GTK, girara and zathura"
MPKG_HOMEPAGE="https://mesonbuild.com/"
MPKG_DEPENDS=(uv ninja)

MPKG_GITHUB_REPO="mesonbuild/meson"
MPKG_DESTDIR='meson-${version}'

mpkg_discover() {
    mpkg_super discover || return 1
    MPKG_ASSET_STEM="meson-${MPKG_VERSION}"
    MPKG_ASSET_FILE="${MPKG_ASSET_STEM}.tar.gz"
    MPKG_ASSET_URL="https://github.com/${MPKG_GITHUB_REPO}/releases/download/${MPKG_TAG}/${MPKG_ASSET_FILE}"
}

mpkg_install() {
    local dest="${MPKG_SOFT}/${MPKG_DEST_NAME}"
    [[ -f "${MPKG_ASSET_STEM}/meson.py" ]] || { mpkg::err "archive did not contain ${MPKG_ASSET_STEM}/meson.py"; return 1; }
    rm -rf "${dest}"
    mkdir -p "${dest}/bin" "${dest}/libexec" || return 1
    # meson.py and its package are all it runs; the tarball's test cases alone
    # are thousands of files.
    mkdir -p "${dest}/libexec/meson" || return 1
    cp -a "${MPKG_ASSET_STEM}/meson.py" "${MPKG_ASSET_STEM}/mesonbuild" "${dest}/libexec/meson/" || return 1
    [[ -f "${MPKG_ASSET_STEM}/man/meson.1" ]] \
        && mkdir -p "${dest}/share/man/man1" \
        && install -m 644 "${MPKG_ASSET_STEM}/man/meson.1" "${dest}/share/man/man1/meson.1"

    cat > "${dest}/bin/meson" <<LAUNCHER
#!/bin/sh
# Generated by mpkg: run Meson ${MPKG_VERSION} from its source tree.
for py in python3 "${MPKG_PREFIX}"/bin/python3.*; do
    if command -v "\${py}" >/dev/null 2>&1; then
        exec "\${py}" "${dest}/libexec/meson/meson.py" "\$@"
    fi
done
echo "meson: no python3 found (install one with: mpkg install uv)" >&2
exit 127
LAUNCHER
    chmod 755 "${dest}/bin/meson" || return 1
    mpkg::step "installed into ${dest}"
}

mpkg_verify() {
    "${MPKG_SOFT}/${MPKG_DEST_NAME}/bin/meson" --version >/dev/null 2>&1 && return 0
    mpkg::err "the new meson does not run (is there a python3?)"
    return 1
}
