# mpkg / lib/shell.sh — what installed packages add to the shell environment.
#
# A package declares its environment in MPKG_ENV, one directive per element;
# the value is a template expanded when the shell starts, so it may use
# ${HOME}, ${MPKG_PREFIX} and other variables, and POSIX defaults:
#
#   path    <VAR> <dir>     move <dir> to the front of the list <VAR>, if it exists
#   set     <VAR> <value>   export VAR=value
#   default <VAR> <value>   export VAR=value, unless VAR is already set
#
#   MPKG_ENV=(
#       'default GOPATH ${HOME}/go'
#       'path PATH ${GOBIN:-${GOPATH%%:*}/bin}'
#   )
#
# Anything a directive cannot say goes in mpkg_shell_env, which prints POSIX
# sh for the environment, and mpkg_shell_rc, which prints POSIX sh for
# interactive shells only (prompts, plugins, shell functions). MPKG_SHELL_ORDER
# (default 50) places a package's fragments among the others.
#
# On install mpkg writes them to $MPKG_STATE/shell/env.d/NN-<pkg>.sh and
# rc.d/NN-<pkg>.sh; shell/env.sh and shell/interactive.sh load those. mpkg
# sources the same env.sh before it builds, so what a shell sees and what a
# build sees cannot drift apart.

mpkg::shell_dir()   { printf '%s/shell' "${MPKG_STATE}"; }
mpkg::shell_env_file() { printf '%s/shell/env.sh' "${MPKG_HOME}"; }

# What a startup file needs to load mpkg: env, or all (env and interactive).
# The prefix is the one thing it must know.
mpkg::shell_block() {
    printf 'export MPKG_PREFIX="%s"\n' "${MPKG_PREFIX}"
    printf '[ -f "${MPKG_PREFIX}/share/mpkg/env.sh" ] && . "${MPKG_PREFIX}/share/mpkg/env.sh"\n'
    [[ "${1:-all}" == all ]] && \
        printf '[ -f "${MPKG_PREFIX}/share/mpkg/interactive.sh" ] && . "${MPKG_PREFIX}/share/mpkg/interactive.sh"\n'
    return 0
}

# Load the environment of everything installed into this process.
mpkg::env_load() {
    local f; f="$(mpkg::shell_env_file)"
    # shellcheck source=/dev/null
    [[ -r "${f}" ]] && . "${f}"
    hash -r 2>/dev/null
    return 0
}

# MPKG_ENV of the loaded class as POSIX sh.
mpkg::shell_directives() {
    local d op var val
    for d in "${MPKG_ENV[@]}"; do
        read -r op var val <<< "${d}"
        if ! [[ "${var}" =~ ^[A-Za-z_][A-Za-z0-9_]*$ && -n "${val}" && "${val}" != *[\"\`]* ]]; then
            mpkg::warn "${MPKG_NAME}: bad MPKG_ENV directive '${d}'"
            continue
        fi
        case "${op}" in
            path)    printf 'mpkg_path %s "%s"\n' "${var}" "${val}" ;;
            set)     printf 'export %s="%s"\n' "${var}" "${val}" ;;
            default) printf '[ -n "${%s:-}" ] || export %s="%s"\n' "${var}" "${var}" "${val}" ;;
            *)       mpkg::warn "${MPKG_NAME}: unknown MPKG_ENV directive '${op}'" ;;
        esac
    done
}

# shell_render <dir> — write the loaded class's fragments under <dir>.
mpkg::shell_render() {
    local into="$1" order body kind
    printf -v order '%02d' "$(( 10#${MPKG_SHELL_ORDER:-50} ))"
    for kind in env rc; do
        if [[ "${kind}" == env ]]; then
            body="$(mpkg::shell_directives; mpkg::optional shell_env)"
        else
            body="$(mpkg::optional shell_rc)"
        fi
        [[ -n "${body//[[:space:]]/}" ]] || continue
        mkdir -p "${into}/${kind}.d" || return 1
        printf '# %s: generated by mpkg from packages/%s.sh. Do not edit.\n%s\n' \
            "${MPKG_NAME}" "${MPKG_NAME}" "${body}" > "${into}/${kind}.d/${order}-${MPKG_NAME}.sh"
    done
}

# Drop <pkg>'s fragments from <dir> (default: the live ones).
mpkg::shell_forget() {
    local name="$1" into="${2:-$(mpkg::shell_dir)}" f
    for f in "${into}"/env.d/[0-9][0-9]-"${name}".sh "${into}"/rc.d/[0-9][0-9]-"${name}".sh; do
        [[ -e "${f}" ]] && rm -f "${f}"
    done
    return 0
}

# After an install: the loaded class's fragments replace its old ones, and
# this process picks them up for the packages built after it.
mpkg::shell_write() {
    mpkg::shell_forget "${MPKG_NAME}"
    mpkg::shell_render "$(mpkg::shell_dir)" || { mpkg::warn "${MPKG_NAME}: could not write its shell fragments"; return 0; }
    mpkg::env_load
}

# Fragments of every installed package, freshly rendered under <dir>. Each
# class is loaded in a subshell so none of them leaks into this process.
mpkg::shell_render_all() {
    local into="$1" p
    mkdir -p "${into}/env.d" "${into}/rc.d" || return 1
    while IFS= read -r p; do
        mpkg::exists "${p}" || continue
        ( mpkg::class_load "${p}" >/dev/null 2>&1 && mpkg::shell_render "${into}" ) 2>/dev/null
    done < <(mpkg::db_list)
}

# Fragments that differ between what is live and what the packages declare:
# "<file> missing|stale|orphan", one per line.
mpkg::shell_diff() {
    local want="$1" have; have="$(mpkg::shell_dir)"
    local f rel
    for f in "${want}"/env.d/*.sh "${want}"/rc.d/*.sh; do
        [[ -e "${f}" ]] || continue
        rel="${f#"${want}"/}"
        if [[ ! -f "${have}/${rel}" ]]; then printf '%s missing\n' "${rel}"
        elif ! cmp -s "${f}" "${have}/${rel}"; then printf '%s stale\n' "${rel}"
        fi
    done
    for f in "${have}"/env.d/*.sh "${have}"/rc.d/*.sh; do
        [[ -e "${f}" ]] || continue
        rel="${f#"${have}"/}"
        [[ -f "${want}/${rel}" ]] || printf '%s orphan\n' "${rel}"
    done
}

# Regenerate every fragment from the installed packages' declarations.
mpkg::shell_sync() {
    local dir tmp
    dir="$(mpkg::shell_dir)"
    tmp="${dir}.new.$$"
    rm -rf "${tmp}"
    mpkg::shell_render_all "${tmp}" || { rm -rf "${tmp}"; return 1; }
    rm -rf "${dir}.old.$$"
    [[ -d "${dir}" ]] && mv "${dir}" "${dir}.old.$$"
    mv "${tmp}" "${dir}" && rm -rf "${dir}.old.$$"
    mpkg::step "shell fragments: $(ls "${dir}/env.d" | wc -l | tr -d ' ') environment, $(ls "${dir}/rc.d" | wc -l | tr -d ' ') interactive"
    mpkg::env_load
}
